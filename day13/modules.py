import math
from random import randint, choice
import random as rnd

print(math.sqrt(16))          # 4.0
print(math.pi)                # 3.14159...
print(math.ceil(4.2))         # 5

print(randint(1, 10))         # random int from 1 to 10
print(choice(["a", "b", "c"]))
print(rnd.random())           # float from 0 to 1s